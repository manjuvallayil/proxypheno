from __future__ import annotations

import json
from pathlib import Path

import pandas as pd


def _round(value, digits: int = 2):
    try:
        return round(float(value), digits)
    except (TypeError, ValueError):
        return None


def brief_for_signature(row: pd.Series) -> dict:
    signature = str(row.get("signature", "unknown"))
    n = int(row.get("n", 0))
    novelty = _round(row.get("novelty_mean"))
    top_traits = row.get("top_traits", "not available")
    enrichment = _round(row.get("max_carrier_enrichment"))
    q_value = _round(row.get("min_q_value"), 4)
    direction = "low" if signature.startswith("low_") else "high"
    trait = signature.split("_", 1)[1] if "_" in signature else signature
    return {
        "signature": signature,
        "n": n,
        "summary": (
            f"{n} animals share a {direction} {trait} residual signature "
            f"(mean novelty score {novelty}). The most distinctive traits are "
            f"{top_traits}. The strongest carrier enrichment in this signature is "
            f"{enrichment} (q={q_value}). This is a discovery-support signal, not a diagnosis."
        ),
        "evidence": {
            "signature": signature,
            "n": n,
            "novelty_mean": novelty,
            "top_traits": top_traits,
            "max_carrier_enrichment": enrichment,
            "min_q_value": q_value,
            "top_mutation": row.get("top_mutation"),
        },
        "suggested_follow_up": (
            "Review carrier status for the prioritised loci, check data quality for "
            "the distinctive traits, and compare against held-out animals."
        ),
        "limitations": (
            "Phenotypes are pre-adjusted yield deviations; the analysis is observational "
            "and does not establish causality. Some known QTL effects are attenuated in "
            "this deposit."
        ),
    }


def research_memo(signature_summary: pd.DataFrame, metrics: dict) -> dict:
    if signature_summary.empty:
        return {"title": "ProxyPheno signature summary", "note": "No signatures available."}
    top = signature_summary.sort_values("n", ascending=False).iloc[0]
    return {
        "title": "ProxyPheno signature summary",
        "n_animals": metrics.get("n_animals"),
        "n_traits_novelty": metrics.get("n_traits_novelty"),
        "n_signatures": int(signature_summary["signature"].nunique()),
        "largest_signature": str(top["signature"]),
        "stability": metrics.get("novelty_stability"),
        "positive_control": metrics.get("positive_control"),
        "note": (
            "Generated from structured signature summaries. All numbers are injected "
            "from the pipeline; no values are generated by a language model."
        ),
    }


def precompute_briefs(
    signature_summary: pd.DataFrame, output_path: Path, metrics: dict | None = None
) -> dict:
    metrics = metrics or {}
    briefs = {
        "signatures": {
            str(row["signature"]): brief_for_signature(row)
            for _, row in signature_summary.iterrows()
        },
        "memo": research_memo(signature_summary, metrics),
    }
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(briefs, indent=2))
    return briefs
